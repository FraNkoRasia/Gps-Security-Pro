export function traducirTextoInterfaz(texto: string): string {
  const normalizado = texto.replace(/\s+/g, ' ').trim()
  if (!normalizado) return texto

  const traduccion = traduccionesInterfazEn[normalizado]
  if (traduccion !== undefined) {
    // Preserva espacios que separan fragmentos JSX de texto dinámico
    // (por ejemplo, "¿Deseas " + estado + " a " + nombre).
    const inicio = texto.match(/^\s*/)?.[0] ?? ''
    const fin = texto.match(/\s*$/)?.[0] ?? ''
    return `${inicio}${traduccion}${fin}`
  }

  // Algunos nodos incluyen una etiqueta fija seguida de datos dinámicos.
  // Solo traducimos el prefijo conocido y dejamos nombres/valores intactos.
  const prefijosDinamicos: Array<[string, string]> = [
    ['Activos (', 'Active ('],
    ['Inactivos (', 'Inactive ('],
    ['Ficha del vigilador:', 'Security Guard File:'],
    ['Historial operativo:', 'Operational History:'],
    ['Historial de Asignaciones:', 'Assignment History:'],
    ['Reasignación de servicio para', 'Service reassignment for'],
    ['No se pudo cargar la ficha técnica del perfil:', 'Could not load the profile personnel file:'],
    ['No se pudo cargar el registro del vigilador:', 'Could not load the security guard record:'],
    ['No se pudo cargar la ficha:', 'Could not load the file:'],
    ['Error al invocar instalación PWA:', 'Error launching PWA installation:'],
  ]
  for (const [prefijo, traduccionPrefijo] of prefijosDinamicos) {
    if (normalizado.startsWith(prefijo)) {
      const inicio = texto.match(/^\\s*/)?.[0] ?? ''
      const fin = texto.match(/\\s*$/)?.[0] ?? ''
      const contenido = texto.trim()
      return `${inicio}${contenido.replace(prefijo, traduccionPrefijo)}${fin}`
    }
  }

  return texto
}

export function traducirAtributoInterfaz(texto: string): string {
  const normalizado = texto.replace(/\s+/g, ' ').trim()
  const exacta = traduccionesAtributosEn[normalizado] ?? traduccionesInterfazEn[normalizado]
  if (exacta) return exacta

  // Algunos atributos incorporan nombres o fechas dinámicas; traducimos solo
  // el texto fijo y conservamos intactos esos valores.
  const patrones: Array<[RegExp, (coincidencia: RegExpMatchArray) => string]> = [
    [/^Ver ficha de (.+)$/, (m) => `View personnel file for ${m[1]}`],
    [/^Ver ficha del vigilador$/, () => 'View security guard file'],
    [/^Restablecer contraseña de (.+)$/, (m) => `Reset password for ${m[1]}`],
    [/^Quitar feriado el (.+)$/, (m) => `Remove holiday on ${m[1]}`],
    [/^Marcar feriado el (.+)$/, (m) => `Mark holiday on ${m[1]}`],
    [/^(.+) de (.+), feriado: (.+)$/, (m) => `${m[1]} ${m[2]}, holiday: ${m[3]}`],
    [/^(.+) de (.+)$/, (m) => `${m[1]} of ${m[2]}`],
  ]
  for (const [patron, traducir] of patrones) {
    const coincidencia = normalizado.match(patron)
    if (coincidencia) return traducir(coincidencia)
  }
  return texto
}
